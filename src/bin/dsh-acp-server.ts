#!/usr/bin/env node
/**
 * DSH ACP Gateway — one-command ACP server.
 *
 * Boots a private DSH instance that exposes the dsh-acp-gateway plugin and
 * serves the ACP protocol directly over this process's stdio.
 *
 * By default the server shares the user's real deployment home (`~/.dsh`):
 * agent presets (including locally authored ones like `anchored-standard`),
 * settings (default model, default preset, permission), sessions, and
 * credentials are all the same ones the web GUI uses, so every feature works
 * identically. Set `DSH_ACP_HOME` to isolate (e.g. `~/.dsh-acp`) when a
 * separate deployment is wanted:
 *
 *   - DSH_HOME → $HOME/.dsh (shared; override with DSH_ACP_HOME)
 *   - webServer → 127.0.0.1:0 (OS-assigned random loopback port)
 *
 * The composition is the official `dsh-base` bundle (the same agent stack a
 * `dsh web` profile mounts: LLM runtime, credentials, tools, agent registry,
 * commands, plan mode, ...) plus a loopback-only webServer and the ACP
 * gateway. The model provider defaults to `opencode-go`; set
 * `DEEPSEEK_API_KEY` (or use `--provider`/`--model` flags) for
 * `deepseek-official`.
 *
 * Usage:
 *   dsh-acp-server
 *
 * Stdout is reserved for ACP JSON-RPC; all diagnostics go to stderr.
 */
import http from 'node:http'
import { parseArgs } from 'node:util'
import { existsSync, mkdirSync, readFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join, dirname } from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'
import { boot, healProfilesModuleFallback, installFailLoud, loadEnv, loadOverlayPatches } from '@deepseek-ai/dsh-app-boot'
import { attachBridge } from '../bridge.js'

const NAME = 'dsh-acp-server'
const here = dirname(fileURLToPath(import.meta.url))

/** Locate the package root that owns `examples/` (source tree or dist build). */
function findPackageRoot(): string {
  let dir = here
  for (let i = 0; i < 5; i += 1) {
    if (existsSync(join(dir, 'examples', 'empty.cordis.yml'))) return dir
    dir = dirname(dir)
  }
  throw new Error(`${NAME}: cannot locate examples/empty.cordis.yml beside ${here}`)
}
const PKG_ROOT = findPackageRoot()
const EMPTY_CONFIG = join(PKG_ROOT, 'examples', 'empty.cordis.yml')

installFailLoud(NAME)
loadEnv(NAME)

// Home: share the user's real deployment by default so presets, settings,
// sessions, and credentials are the same ones the web GUI uses. DSH_ACP_HOME
// opts back into a fully isolated deployment.
const acpHome = process.env.DSH_ACP_HOME || join(homedir(), '.dsh')
mkdirSync(acpHome, { recursive: true })
process.env.DSH_HOME = acpHome
if (!process.env.DSH_ACP_HOME) process.env.DSH_ACP_HOME = acpHome

const { values } = parseArgs({
  args: process.argv.slice(2),
  options: {
    provider: { type: 'string', default: process.env.DSH_ACP_PROVIDER || 'opencode-go' },
    model: { type: 'string', default: process.env.DSH_ACP_MODEL || 'deepseek-v4-flash' },
  },
  strict: true,
})

/** Resolve one npm package to its directory, mirroring Node's parent-walk. */
function resolvePackageDir(specifier: string): string {
  const resolved = import.meta.resolve(specifier + '/package.json')
  return dirname(fileURLToPath(resolved))
}

/**
 * The dsh app installation anchor (its package.json). Lookup order:
 *
 * 1. Resolve `@deepseek-ai/dsh` directly from the package's own node_modules
 *    (npm flattens the dependency into the tree, so `npm i dsh-acp-gateway`
 *    or `npx dsh-acp-gateway` finds it beside this package — the standard
 *    npx-distribution layout). The app declares no `exports`, so the
 *    package.json subpath resolves.
 * 2. The typical global-install layout: dsh-app-boot nested under the dsh
 *    app's own node_modules — ascend three levels and verify the name.
 * 3. The offline bundle's vendor anchor (`vendor/dsh-app/package.json`,
 *    generated by scripts/package-offline.sh).
 */
function dshInstallAnchor() {
  try {
    const dir = resolvePackageDir('@deepseek-ai/dsh')
    const candidate = join(dir, 'package.json')
    const manifest = JSON.parse(readFileSync(candidate, 'utf8'))
    if (manifest.name === '@deepseek-ai/dsh') return candidate
  } catch (e) {
    /* not resolvable from this package's tree */
  }
  try {
    const appBootDir = resolvePackageDir('@deepseek-ai/dsh-app-boot')
    const candidate = join(appBootDir, '..', '..', '..', 'package.json')
    const manifest = JSON.parse(readFileSync(candidate, 'utf8'))
    if (manifest.name === '@deepseek-ai/dsh') return candidate
  } catch (e) {
    /* not the dsh app */
  }
  try {
    const portable = join(PKG_ROOT, 'vendor', 'dsh-app', 'package.json')
    const manifest = JSON.parse(readFileSync(portable, 'utf8'))
    if (manifest.name === '@deepseek-ai/dsh') return portable
  } catch (e) {
    /* no portable bundle */
  }
  return null
}

/**
 * The official dsh-base bundle patch — the complete agent stack (LLM,
 * credentials, session store, tools, agent registry, commands, plan mode,
 * subagents, ...). Loaded from the same package the user's `dsh` installs.
 */
const baseDir = resolvePackageDir('@deepseek-ai/dsh-base')
const baseManifest = JSON.parse(readFileSync(join(baseDir, 'package.json'), 'utf8'))
const basePatchPath = join(baseDir, baseManifest.dsh?.bundle?.patch ?? 'cordis.patch.yml')

/**
 * Agent presets (the `standard` preset the gateway mounts per agent) come from
 * the official `@deepseek-ai/dsh-agent-presets` package: since 0.1.2 the
 * shipped presets moved out of the dsh CLI package into
 * `<pkg>/presets/{standard,minimal,ptc,cordis}`. Fallbacks keep older
 * layouts working: a `config/agent-presets` directory beside the dsh app
 * (pre-0.1.2 npm-flat layout) and the offline bundle's own copy.
 */
function shippedPresetRoot() {
  try {
    const presetPkg = resolvePackageDir('@deepseek-ai/dsh-agent-presets')
    const candidate = join(presetPkg, 'presets')
    return readFileSync(join(candidate, 'standard', 'preset.yml'), 'utf8') ? candidate : null
  } catch (e) {
    /* keep looking */
  }
  try {
    const anchor = dshInstallAnchor()
    if (anchor) {
      const candidate = join(dirname(anchor), 'config', 'agent-presets')
      return readFileSync(join(candidate, 'standard', 'preset.yml'), 'utf8') ? candidate : null
    }
  } catch (e) {
    /* keep looking */
  }
  // Portable fallback: the offline bundle ships the shipped presets beside
  // its own config.
  try {
    const candidate = join(PKG_ROOT, 'config', 'agent-presets')
    return readFileSync(join(candidate, 'standard', 'preset.yml'), 'utf8') ? candidate : null
  } catch (e) {
    return null
  }
}

// Boot with the empty composition patched by: the official dsh-base bundle
// (unchanged), then our overlays (HMR off, loopback webServer, agent presets
// root, provider route, and the ACP gateway). Stdout stays pure for ACP
// JSON-RPC.
const presetRoot = shippedPresetRoot()
const provider = values.provider
// When the home has no settings document (isolated `DSH_ACP_HOME`), a pi-ai
// provider route is declared directly on the adapter row. With a shared home
// the deployment's own llm-pi-ai settings layer already carries the routes.
// `deepseek-official` is the dedicated llm-deepseek adapter (DEEPSEEK_API_KEY)
// and needs no pi-ai route.
const apiKeyEnv = provider === 'deepseek-official' ? 'DEEPSEEK_API_KEY' : `${provider.replace(/-/g, '_').toUpperCase()}_API_KEY`
const patches = [
  ...loadOverlayPatches(NAME, basePatchPath),
  { id: 'hmr', disabled: true },
  // The default-model row only seeds the base (bundle default: deepseek-official)
  // when the home has no settings document; a shared home's `agent-default-model`
  // settings section overrides it live.
  { id: 'agent-default-model', config: { provider, model: values.model } },
  ...(provider === 'deepseek-official'
    ? []
    : [{ id: 'llm-pi-ai', config: { providers: { [provider]: { apiKeyEnv } } } }]),
  {
    insert: [
      { id: 'webserver', name: '@deepseek-ai/dsh-host-webserver', config: { host: '127.0.0.1', port: 0 } },
      // The shipped preset root only; the service appends the home's own
      // `.agent-presets` user root automatically, so a shared home sees the
      // same roster (and default) as the web GUI. `default` is the row's base
      // (the web profile declares `standard`); a shared home's settings layer
      // (`agent-presets.default`) overrides it live. includeShippedRoot stays
      // false so this explicitly resolved root is the only system layer (the
      // package's bundled presets are the same directory resolution reachable
      // through the dsh CLI, and mounting them twice would duplicate ids).
      ...(presetRoot
        ? [{ id: 'agent-presets', name: '@deepseek-ai/dsh-agent-presets', config: { default: 'standard', roots: [{ path: presetRoot, trust: 'system' }], includeShippedRoot: false, includeUserRoot: true } }]
        : []),
      {
        id: 'acp-gateway',
        name: '../dist/src/index.js',
        config: {
          provider,
          model: values.model,
          stdioScriptPath: join(acpHome, 'acp', 'dsh-acp-agent.js'),
        },
      },
    ],
  },
]

// Bare package resolution: the official dsh CLI keeps one flat symlink
// directory per home ($DSH_HOME/profiles/node_modules) that mirrors every
// package the dsh app and its bundles depend on. Maintain it in the target
// home (idempotent — with a shared home the existing web-profile directory
// is reused) and hand it to the loader as the bare-module base, exactly
// like `dsh --profile web` does.
const anchor = dshInstallAnchor()
if (anchor === null) {
  process.stderr.write(`${NAME}: cannot locate the @deepseek-ai/dsh installation (needed for the dsh-base bundle and its dependencies)\n`)
  process.exit(1)
}
await healProfilesModuleFallback({ installAnchor: anchor, home: acpHome })
const bareModuleBaseUrl = pathToFileURL(join(acpHome, 'profiles', 'node_modules') + '/').href

const ctx = await boot(NAME, EMPTY_CONFIG, patches, undefined, bareModuleBaseUrl)

/** Wait until the gateway's loopback route answers (it mounts after apply). */
async function waitForGateway(endpoint: string, timeoutMs = 20000): Promise<void> {
  const deadline = Date.now() + timeoutMs
  while (Date.now() < deadline) {
    try {
      const ok = await new Promise<boolean>((resolve) => {
        const req = http.request(`${endpoint}/acp/rpc`, { method: 'POST', headers: { 'content-type': 'application/json' } }, (res) => {
          res.resume()
          // 404/405 = route not mounted yet; anything else means the gateway answers.
          resolve(res.statusCode !== undefined && res.statusCode !== 404 && res.statusCode !== 405)
        })
        req.setTimeout(2000, () => req.destroy())
        req.on('error', () => resolve(false))
        req.end('{"jsonrpc":"2.0","id":0,"method":"initialize","params":{}}')
      })
      if (ok) return
    } catch (e) {
      /* retry */
    }
    await new Promise((r) => setTimeout(r, 500))
  }
}

// Once the loopback server is up, serve ACP JSON-RPC over our own stdio.
;(ctx.inject as any)(['webServer'], (webCtx: any) => {
  const endpoint = `http://127.0.0.1:${webCtx.webServer.port}`
  process.stderr.write(`dsh-acp-server: loopback ${endpoint} (stdin/stdout ACP)\n`)
  void waitForGateway(endpoint).then(() => {
    attachBridge(process.stdin, process.stdout, endpoint, () => {
      void ctx.fiber.dispose().then(() => process.exit(0))
    })
  })
})
